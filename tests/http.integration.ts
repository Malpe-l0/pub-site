function action(html:string,marker:string) {
  const form=[...html.matchAll(/<form\b[^>]*>([\s\S]*?)<\/form>/g)].map(x=>x[1]).find(x=>x.includes(marker))
  assert(form,`Modulo non trovato: ${marker}`)
  const id=form.match(/name="(\$ACTION_ID_[^"]+)"/)
  assert(id,'ID Server Action assente')
  return id[1]
}
async function post(url:string,id:string,values:Record<string,string|File>,cookie='') {
  const form=new FormData();form.set(id,'')
  for(const [key,value] of Object.entries(values)) form.set(key,value)
  return fetch(base+url,{method:'POST',body:form,headers:headers(cookie),redirect:'manual'})
}
